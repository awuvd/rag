"""
week2_D13.py —— T7：最小检索（输入问题 → 返回最相关的知识块）
================================================================
作用：连上 D12 建好的向量库，把用户的问题编码成向量，
      找出最相似的 5 个知识块，打印出来（带距离 + 溯源）。

运行：py week2_D13.py
输入：你在终端输入一个问题（比如"什么是注意力机制"）
输出：终端打印 top-5 结果

前置：data/chunks.json 已被 D12 编码入库（chroma_db/ 里有 1023 条）

运行结果示例：
    #1 距离=0.4994|第8章注意力机制与外部记忆|以作用在内部的意识（思考、回忆等）...
    #2 距离=0.5266|第8章注意力机制与外部记忆|指自上而下的聚焦式注意力...
    ...（5 条全部来自第 8 章，说明检索正确）

【本文件踩过的 3 个坑（都很典型，值得记住）】
  坑 1：环境变量必须在 import sentence_transformers【之前】设置
  坑 2：必须用 query_embeddings，不能用 query_texts
        —— 否则 Chroma 会用自带的英文模型编码，和 BGE 向量空间不匹配
  坑 3：query() 返回的是【两层嵌套列表】，要用 [0] 取"第 1 个查询"的结果
"""

import os

# ⚠️ 坑 1：环境变量必须在 import sentence_transformers 之前设置！
#   因为 huggingface_hub 在【被导入的那一刻】就读取这些变量。
#   HF_HUB_OFFLINE='1' → 强制离线：模型已缓存在本地，别去网上检查更新
#   （否则会尝试联网，然后超时重试，白白等很久）
os.environ['HF_HUB_OFFLINE'] = '1'

import chromadb
from sentence_transformers import SentenceTransformer

# ============================================================
# ① 准备：加载模型 + 连接向量库
# ============================================================

# 加载 BGE 中文向量化模型（和 D12 入库时用的是同一个）
model = SentenceTransformer('BAAI/bge-base-zh-v1.5')

# PersistentClient = 持久化客户端，连上【磁盘上】的向量库
# 这个库里存着 D12 写入的 1023 个知识块（原文 + 向量 + 元信息）
client = chromadb.PersistentClient(path=r"E:\llm-study-plan\rag\chroma_db")

# ⭐ 用 get_collection 而不是 get_or_create_collection：
#   如果名字打错了，get_collection 会【直接报错】，问题立刻暴露；
#   而 get_or_create 会【默默创建一个空集合】→ 你查询返回 0 条，还找不到原因
col = client.get_collection('nndl_book')

# ============================================================
# ② 拿到用户的问题
# ============================================================
q_vecs = []
q_vecs.append(input("你的问题是什么"))
# 💡 为什么要放进列表？
#   因为后面编码出来要的是二维形状 (1, 768)，而不是一维 (768,)
#   传列表 → 二维；传单个字符串 → 一维。query() 要的是二维。

# ============================================================
# ③ 编码问题：文本 → 向量（关键：必须和入库时完全一致）
# ============================================================
q_vec = model.encode(q_vecs, normalize_embeddings=True)
#                        ↑输入              ↑配置
#   【输入】是你的问题（和入库时的 1023 个块不同 —— 数据本来就可以不同）
#   【配置】必须和 D12 入库时一模一样！归一化的意义：
#      把向量长度缩成 1 → 之后"点积"直接等于"余弦相似度"（省掉除法，更快）
#
#   形状 (1, 768)：1 个问题 × 768 维（768 是 BGE 模型的固定输出维度）
print(q_vec.shape)

# ============================================================
# ④ 向量转成 Python 列表
# ============================================================
# model.encode() 返回的是 numpy 数组，而 Chroma 只认【普通 Python 列表】
# （和 D12 传给 add(embeddings=...) 时做的是同一个转换）
q_vec1 = q_vec.tolist()

# ============================================================
# ⑤ 检索：让 Chroma 找出最接近的 5 个知识块
# ============================================================
# ⚠️ 坑 2：必须传 query_embeddings（我们自己编码好的向量）！
#   如果传 query_texts（直接给文本），Chroma 会用它【自带的默认模型】编码，
#   那是个【英文模型】(all-MiniLM-L6-v2)，和你的 BGE 向量空间完全不匹配
#   → 结果全乱。而且它【不会报错】，非常隐蔽！
#
#   n_results=5：返回最相似的 5 条
#     太小(1~2) → 可能漏掉相关块
#     太大(20+) → 塞给大模型太多无关内容，反而干扰生成（还费 token）
res = col.query(query_embeddings=q_vec1, n_results=5)

# 返回值是个字典，键有：ids / documents / metadatas / distances / embeddings / ...
print(res.keys())

# ============================================================
# ⑥ 解析返回结构（⚠️ 坑 3：两层嵌套！）
# ============================================================
# res['documents'] 长这样：
#     [ ['文本1', '文本2', '文本3', '文本4', '文本5'] ]
#       ↑ 外层：第几个查询（query 支持一次问多个问题，省时间）
#          ↑ 内层：那一个问题的 5 条结果
#
# 我们只问了 1 个问题 → 外层长度是 1 → 取 [0] 拿出"第 1 个查询"的结果
docs  = res['documents'][0]     # 命中的原文（5 条）
metas = res['metadatas'][0]     # 对应的元信息（5 条）：{chapter, title, chunk_index}
dists = res['distances'][0]     # 对应的距离（5 条）：越小 = 越相似

# ============================================================
# ⑦ 逐条打印（带溯源）
# ============================================================
# 两个工具合用：
#   zip       → 把三个【平行列表】对齐，一次循环同时拿到 原文 + 元信息 + 距离
#   enumerate → 再配一个序号 i（start=1 表示从 1 开始编号）
for i, (doc, meta, dist) in enumerate(zip(docs, metas, dists), start=1):
    ch = meta['chapter']        # 元信息是字典 → 用 ['键名'] 取值
    title = meta['title']
    # f-string 里三处格式化：
    #   {i}         序号
    #   {dist:.4f}  距离保留 4 位小数
    #               ⚠️ 注意那个【小数点】！`.4` 才是"4位小数"；
    #                  写成 `4f` 是"最小宽度 4"，小数位数会用默认的 6 位
    #   {doc[:60]}  只取前 60 个字符（一个块有 500 字，全打会刷屏）
    print(f"#{i} 距离={dist:.4f}|第{ch}章{title}|{doc[:60]}")

# ============================================================
# 📌 小结：今天学到的 3 件事
# ============================================================
# 1. 编码查询 = 和入库时【完全相同的模型 + 完全相同的配置】
#    （数据可以不同：问题是 1 条、库是 1023 条；但"尺子"必须相同）
# 2. 必须用 query_embeddings —— 自己编码，绝不让库替你编码
# 3. 返回是两层嵌套，取 [0] 才是"第 1 个查询"的结果
#
# 💡 延伸：现在显示的距离是【L2 欧氏距离】（因为建库时没指定距离度量）。
#    对归一化向量，L2 和余弦相似度有换算关系： cos = 1 - L2² / 2
#    例：距离 0.4994 → 余弦相似度 ≈ 0.875（相当相关）
#    如果建库时指定 metadata={'hnsw:space': 'cosine'}，距离会直接显示成
#    1-cos = 0.125，一眼就能看出相关性（排序其实是一样的）
